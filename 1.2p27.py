#suivez la variabe q'affiche le programme suivant l'orsqu'on l'excute
a = 1
b = 2
a = b
b = a
print(a, b)
#Le programme affiche 2 2 car:
#- initialement, a est 1 et b est 2
#- ensuite, a est mis à la valeur de b, donc a devient 2
#- puis, b est mis à la valeur de a (qui est maintenant 2), donc b reste 2
#Ainsi, l'affichage final est "2 2"
