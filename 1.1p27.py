#Opération à la chaine qu'affiche le programme suivant l'orsqu'on l'excute
nombre_1 = 5
nombre_2 = nombre_1 + nombre_1
nombre_3 = nombre_2 * nombre_1
print(nombre_1, nombre_2, nombre_3)
#Le programme affiche 5 10 50 car:
#- nombre_1 est initialisé à 5
#- nombre_2 est calculé en ajoutant nombre_1 à lui-même, donc 5 + 5 = 10
#- nombre_3 est calculé en multipliant nombre_2 par nombre_1
#  donc 10 * 5 = 50
#Ainsi, l'affichage final est "5 10 50"
